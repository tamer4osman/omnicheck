/* Sprint 6 (M5 GA scope) tests: fuzz targets + corpus hardening (WBS
 * 5.1). Three layers, all deterministic and bounded:
 *
 *  1. Seeded mutation fuzz IN-PROCESS through the shared scan pipeline
 *     (oc_scan_run): committed seed table drives byte-level mutations of
 *     the regular fixtures; every mutated tree is scanned twice and the
 *     report bytes must be identical (determinism under corruption), the
 *     findings must stay canonically sorted, and the result must destroy
 *     cleanly (LeakSanitizer proves it in the sanitize cell).
 *  2. Committed adversarial corpus (tests/%s, generated by
 *     scripts/gen_fuzz_corpus.py) run through the real oc binary: exit
 *     codes stay in {0,1,2}, no crash, and whenever exit is 2 the stderr
 *     carries the warning AND the report meta names the parse errors --
 *     the no-silent-partial-analysis contract under attack.
 *  3. Loader fuzz: every malformed JSON fixture goes through the strict
 *     JSON parser (in-process, fresh arena) and, via the CLI, through the
 *     coverage and OSV loaders. Malformed input must produce honest
 *     errors, never crashes, never silent skips.
 */
