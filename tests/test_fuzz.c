static int check_count = 0;
static int check_fail = 0;
#define CHECK(cond)                                                                                \
    do {                                                                                           \
        check_count++;                                                                             \
        if (!(cond)) {                                                                             \
            fprintf(stderr, "  FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond);                      \
            check_fail++;                                                                          \
        }                                                                                          \
    } while (0)
#define TEST_SUMMARY()                                                                             \
    fprintf(stderr, "%s: %d checks, %d failures\n", __FILE__, check_count, check_fail)

/* ------------------------------------------------------ seeded PRNG ---- */

/* xorshift64*; the seed table is COMMITTED, so any failing case is
 * reproducible by seed alone (fuzzing here never depends on wall clock
 * or ASLR). */
static unsigned long long rng_state;

static void rng_seed(unsigned long long seed) {
    rng_state = seed;
}

static unsigned long long rng_next(void) {
    rng_state ^= rng_state >> 12;
    rng_state ^= rng_state << 25;
    rng_state ^= rng_state >> 27;
    return rng_state * 0x2545F4914F6CDD1DULL;
}

static size_t rng_below(size_t n) {
    return (size_t)(rng_next() % (unsigned long long)n);
}

/* ----------------------------------------------------- mutation ops ---- */

/* Mutations are applied over a scratch copy; every op either produces a
 * valid weird file or a fully corrupt one -- both must be handled
 * honestly by the pipeline. */
static size_t mutate_bytes(unsigned char *buf, size_t len, size_t cap) {
    switch (rng_next() % 6) {
    case 0: /* flip: XOR a random byte with a random mask */
        if (len == 0)
            break;
        buf[rng_below(len)] ^= (unsigned char)(1u << rng_below(8));
        break;
    case 1: /* insert a random byte at a random offset */
        if (len + 1 > cap)
            break;
        {
            size_t at = rng_below(len + 1);
            memmove(buf + at + 1, buf + at, len - at);
            buf[at] = (unsigned char)rng_next();
            len++;
        }
        break;
    case 2: /* truncate at a random point (keep at least one byte) */
        if (len > 1)
            len = 1 + rng_below(len);
        break;
    case 3: /* duplicate a block of up to 64 bytes onto another spot */
        if (len + 64 > cap || len == 0)
            break;
        {
            size_t from = rng_below(len);
            size_t n = 1 + rng_below(64);
            if (from + n > len)
                n = len - from;
            size_t at = rng_below(len + 1);
            if (at + n > cap)
                n = cap - at;
            memmove(buf + at, buf + from, n);
            if (at + n > len)
                len = at + n;
        }
        break;
    case 4: /* NUL injection */
        if (len + 4 > cap)
            break;
        {
            size_t at = rng_below(len + 1);
            memmove(buf + at + 4, buf + at, len - at);
            memset(buf + at, 0, 4);
            len += 4;
        }
        break;
    case 5: /* byte storm: up to 8 single-byte flips */
        for (int i = 0; i < 8 && len > 0; i++)
            buf[rng_below(len)] ^= (unsigned char)(rng_next() | 1u);
        break;
    }
    return len;
}

/* ------------------------------------------------------ scan helpers --- */

static int findings_sorted(const oc_scan_result *res) {
    for (size_t i = 1; i < res->findings.n; i++) {
        const oc_finding *a = &res->findings.items[i - 1];
        const oc_finding *b = &res->findings.items[i];
        int c = strcmp(a->file ? a->file : "", b->file ? b->file : "");
        if (c > 0)
            return 0;
        if (c == 0) {
            if (a->line > b->line)
                return 0;
            if (a->line == b->line && a->col > b->col)
                return 0;
        }
    }
    return 1;
}

static void write_report(oc_strbuf *out, const oc_scan_result *res) {
    oc_jsonw w;
    oc_jsonw_init(&w);
    oc_report_write_json(&w, res);
    oc_strbuf_append(out, w.buf.data, w.buf.len);
    oc_jsonw_destroy(&w);
}

static oc_arena g_arena;

/* ------------------------------------------------------ layer 1: fuzz -- */

static void write_tree(const char *root, const unsigned char *data_a, size_t len_a,
                       const unsigned char *data_b, size_t len_b) {
    char p[600];
    snprintf(p, sizeof(p), "%s/a.js", root);
    FILE *f = fopen(p, "wb");
    if (f && len_a)
        fwrite(data_a, 1, len_a, f);
    if (f)
        fclose(f);
    snprintf(p, sizeof(p), "%s/b.py", root);
    f = fopen(p, "wb");
    if (f && len_b)
        fwrite(data_b, 1, len_b, f);
    if (f)
        fclose(f);
}

static void test_fuzz_pipeline(void) {
    /* Mutations seed off the committed example corpus (always present):
     * examples/js/demo.js + examples/py/demo.py -- one file per grammar, so
     * every mutation reaches both grammars' error recovery. */
    {
        size_t la = 0, lb = 0;
        unsigned char *fa = NULL;
        char path[512];
        snprintf(path, sizeof(path), "%s/examples/js/demo.js", OC_REPO_ROOT);
        FILE *f = fopen(path, "rb");
        CHECK(f != NULL);
        if (!f)
            return;
        fseek(f, 0, SEEK_END);
        la = (size_t)ftell(f);
        fseek(f, 0, SEEK_SET);
        fa = malloc(la ? la : 1);
        if (fread(fa, 1, la, f) != la)
            la = 0;
        fclose(f);

        snprintf(path, sizeof(path), "%s/examples/py/demo.py", OC_REPO_ROOT);
        f = fopen(path, "rb");
        CHECK(f != NULL);
        if (!f) {
            free(fa);
            return;
        }
        fseek(f, 0, SEEK_END);
        lb = (size_t)ftell(f);
        fseek(f, 0, SEEK_SET);
        unsigned char *fb = malloc(lb ? lb : 1);
        if (fread(fb, 1, lb, f) != lb)
            lb = 0;
        fclose(f);

        char tmpl[] = "/tmp/oc_fuzz_XXXXXX";
        char *root = mkdtemp(tmpl);
        CHECK(root != NULL);
        if (!root) {
            free(fa);
            free(fb);
            return;
        }

        const char *packs = OC_REPO_ROOT "/packs";
        unsigned char *ma = malloc(la + 4096);
        unsigned char *mb = malloc(lb + 4096);

        static const unsigned long long SEEDS[] = {
            0x5EED0001ULL, 0x5EED0002ULL, 0x5EED0003ULL, 0x5EED0004ULL,
            0x5EED0005ULL, 0x5EED0006ULL, 0x5EED0007ULL, 0x5EED0008ULL,
            0xC0FFEE01ULL, 0xDEADBEEFULL, 0x12345678ULL, 0xABCDEF01ULL,
        };
        const size_t N_SEEDS = sizeof(SEEDS) / sizeof(SEEDS[0]);
        const size_t CASES_PER_SEED = 4;
        size_t executed = 0, hard_errors = 0, parse_error_cases = 0;

        for (size_t s = 0; s < N_SEEDS; s++) {
            for (size_t c = 0; c < CASES_PER_SEED; c++) {
                rng_seed(SEEDS[s] * 1000003ULL + c);
                memcpy(ma, fa, la);
                memcpy(mb, fb, lb);
                size_t mla = mutate_bytes(ma, la, la + 4096);
                size_t mlb = mutate_bytes(mb, lb, lb + 4096);
                write_tree(root, ma, mla, mb, mlb);

                const char *paths[1] = {root};
                oc_scan_options opt;
                memset(&opt, 0, sizeof(opt));
                opt.packs_dir = packs;
                opt.paths = paths;
                opt.n_paths = 1;

                oc_scan_result r1, r2;
                oc_status st1, st2;
                oc_status_clear(&st1);
                oc_status_clear(&st2);
                oc_code c1 = oc_scan_run(&opt, &r1, &st1);
                CHECK(c1 == OC_OK || st1.msg[0] != 0); /* hard errors explain themselves */
                if (c1 != OC_OK) {
                    hard_errors++;
                    oc_scan_result_destroy(&r1);
                    continue;
                }
                CHECK(findings_sorted(&r1));
                if (r1.n_parse_errors > 0)
                    parse_error_cases++;
                for (size_t i = 0; i < r1.findings.n; i++)
                    CHECK(r1.findings.items[i].severity <= OC_SEV_ERROR);

                oc_code c2 = oc_scan_run(&opt, &r2, &st2);
                CHECK(c2 == OC_OK);
                oc_strbuf b1, b2;
                oc_strbuf_init(&b1);
                oc_strbuf_init(&b2);
                write_report(&b1, &r1);
                write_report(&b2, &r2);
                if (!(b1.len == b2.len && memcmp(b1.data, b2.data, b1.len) == 0)) {
                    /* Determinism violation: dump BOTH reports for the
                     * first failing case so the diff is reproducible
                     * (seed is committed). */
                    static int dumped = 0;
                    if (dumped < 3) {
                        FILE *f1 = fopen("/tmp/oc_fuzz_r1.json", "w");
                        FILE *f2 = fopen("/tmp/oc_fuzz_r2.json", "w");
                        if (f1) {
                            fwrite(b1.data, 1, b1.len, f1);
                            fclose(f1);
                        }
                        if (f2) {
                            fwrite(b2.data, 1, b2.len, f2);
                            fclose(f2);
                        }
                        fprintf(stderr,
                                "  seed 0x%016llX case %zu: reports differ "
                                "(dumped to /tmp/oc_fuzz_r{1,2}.json)\n",
                                (unsigned long long)SEEDS[s], c);
                        dumped++;
                    }
                }
                CHECK(b1.len == b2.len && memcmp(b1.data, b2.data, b1.len) == 0);
                oc_strbuf_destroy(&b1);
                oc_strbuf_destroy(&b2);

                oc_scan_result_destroy(&r1);
                oc_scan_result_destroy(&r2);
                executed++;
            }
        }

        fprintf(stderr,
                "  fuzz: %zu mutated cases scanned twice; %zu hard errors, "
                "%zu with parse-error records\n",
                executed, hard_errors, parse_error_cases);
        CHECK(executed == N_SEEDS * CASES_PER_SEED);
        CHECK(parse_error_cases > 0); /* the mutation ops must reach the parser */

        free(ma);
        free(mb);
        free(fa);
        free(fb);

        /* clean the temp tree */
        char p[600];
        snprintf(p, sizeof(p), "%s/a.js", root);
        remove(p);
        snprintf(p, sizeof(p), "%s/b.py", root);
        remove(p);
        rmdir(root);
    }
}

/* -------------------------------------------------- layer 2: corpus ---- */

/* File capture instead of popen: the stress corpus emits multi-MB
 * reports, and a capped pipe reader made the child die with SIGPIPE
 * (exit 141) -- a harness bug the first run caught on itself. Returns a
 * malloc'd stdout buffer (caller frees); *rc is the child exit code. */
static char *run_cmd_capture(const char *cmd, int *rc) {
    char full[1400];
    remove("/tmp/oc_fuzz_err.txt");
    snprintf(full, sizeof(full), "%s > /tmp/oc_fuzz_out.txt 2>/tmp/oc_fuzz_err.txt", cmd);
    int r = system(full);
    *rc = WIFEXITED(r) ? WEXITSTATUS(r) : -1;
    FILE *f = fopen("/tmp/oc_fuzz_out.txt", "rb");
    if (!f)
        return NULL;
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    char *buf = malloc((size_t)n + 1);
    CHECK(buf != NULL);
    if (buf) {
        if (n > 0 && fread(buf, 1, (size_t)n, f) != (size_t)n) {
            CHECK(0); /* truncated capture -- should not happen on a file */
        }
        buf[n] = 0;
    }
    fclose(f);
    remove("/tmp/oc_fuzz_out.txt");
    return buf;
}

/* Loads the captured stderr (bounded); returns its length. */
static size_t read_err(char *out, size_t cap) {
    FILE *e = fopen("/tmp/oc_fuzz_err.txt", "r");
    if (!e)
        return 0;
    size_t n = fread(out, 1, cap - 1, e);
    out[n] = 0;
    fclose(e);
    remove("/tmp/oc_fuzz_err.txt");
    return n;
}

static int rc_honest(int r) {
    return r == 0 || r == 1 || r == 2;
}

static int rc_crashed(int r) {
    return r == 139 || r == 134 || r == 136 || r == 137 || r < 0;
}

static void test_adversarial_corpus(void) {
    const char *oc = OC_OC_BIN;
    char cmd[1100];
    const char *fuzz = OC_REPO_ROOT "/tests/fixtures_fuzz";

    /* The whole corpus in one run (both packs together, like users do). */
    snprintf(cmd, sizeof(cmd), "%s check %s/js %s/py --packs-dir %s", oc, fuzz, fuzz,
             OC_REPO_ROOT "/packs");
    int rc;
    char *out = run_cmd_capture(cmd, &rc);
    size_t out_len = out ? strlen(out) : 0;
    CHECK(rc_honest(rc));
    CHECK(!rc_crashed(rc));
    fprintf(stderr, "  corpus: full-tree exit=%d, report %zu bytes\n", rc, out_len);

    if (rc == 2) {
        /* No silent partial analysis: stderr warned AND the report names
         * the broken files. */
        char err[400];
        size_t ne = read_err(err, sizeof(err));
        CHECK(ne > 0);
        CHECK(strstr(out, "\"parse_errors\"") != NULL);
        CHECK(strstr(out, "parse_error_nodes") != NULL);
    }

    /* Determinism of the corpus report across two runs. */
    int rc2;
    char *out2 = run_cmd_capture(cmd, &rc2);
    CHECK(rc2 == rc);
    CHECK(out && out2 && strcmp(out, out2) == 0);
    free(out2);
    free(out);

    /* Each adversarial file alone must also complete honestly. */
    static const char *FILES[] = {"js/nul_fuzz.js",       "js/bom.js",
                                  "js/only_comments.js",  "js/no_newline.js",
                                  "js/empty.js",          "js/unicode_ident.js",
                                  "js/deep_nest.js",      "js/brace_bomb.js",
                                  "js/huge_line.js",      "js/many_functions.js",
                                  "js/mutated_report.js", "py/invalid_utf8.py",
                                  "py/crlf.py",           "py/mixed_endings.py",
                                  "py/unterminated.py",   "py/empty.py",
                                  "py/long_ident.py",     "py/many_functions.py",
                                  "py/cr_only.py"};
    size_t honest_exit2 = 0;
    for (size_t i = 0; i < sizeof(FILES) / sizeof(FILES[0]); i++) {
        char rel[256];
        snprintf(rel, sizeof(rel), "%s/%s", fuzz, FILES[i]);
        snprintf(cmd, sizeof(cmd), "%s check '%s' --packs-dir %s", oc, rel, OC_REPO_ROOT "/packs");
        int r;
        char *o = run_cmd_capture(cmd, &r);
        CHECK(rc_honest(r));
        CHECK(!rc_crashed(r));
        if (r == 2) {
            honest_exit2++;
            if (!o || strstr(o, "\"parse_errors\"") == NULL) {
                FILE *d = fopen("/tmp/oc_fuzz_single_fail.txt", "w");
                if (d) {
                    fprintf(d, "cmd=%s\nexit=%d\n----\n%s\n----stderr----\n", cmd, r,
                            o ? o : "(null out)");
                    char e[400];
                    read_err(e, sizeof(e));
                    fputs(e, d);
                    fclose(d);
                }
                fprintf(stderr, "  %s: exit=%d capture=%zu bytes (dumped)\n", FILES[i], r,
                        o ? strlen(o) : 0);
            }
            CHECK(strstr(o ? o : "", "\"parse_errors\"") != NULL);
        }
        free(o);
    }
    fprintf(stderr,
            "  corpus: %zu single-file runs completed honestly "
            "(%zu named parse errors)\n",
            sizeof(FILES) / sizeof(FILES[0]), honest_exit2);
}

/* -------------------------------------------------- layer 3: loaders --- */

static void test_json_loader_fuzz(void) {
    static const char *FILES[] = {"json/coverage_truncated.json",
                                  "json/coverage_huge_numbers.json",
                                  "json/coverage_wrong_types.json",
                                  "json/coverage_empty.json",
                                  "json/osv_truncated.json",
                                  "json/osv_wrong_schema.json",
                                  "json/osv_records_not_array.json",
                                  "json/nested_bomb.json",
                                  "json/dup_keys.json",
                                  "json/nul_fuzz.json"};
    for (size_t i = 0; i < sizeof(FILES) / sizeof(FILES[0]); i++) {
        char path[600];
        snprintf(path, sizeof(path), "%s/tests/fixtures_fuzz/%s", OC_REPO_ROOT, FILES[i]);
        char *data = NULL;
        size_t len = 0;
        oc_status st;
        oc_status_clear(&st);
        oc_code rc = oc_read_file(path, &data, &len, &st);
        CHECK(rc == OC_OK);
        if (rc != OC_OK)
            continue;
        oc_arena a;
        oc_arena_init(&a);
        oc_json *j = oc_json_parse(&a, data, len, &st);
        /* Either a DOM or an honest error -- never a crash. When a DOM
         * comes back it must be a complete object/array (no half-parse).
         * The strict parser rejects malformed bytes with st set. */
        if (j) {
            CHECK(st.code == OC_OK || st.msg[0] != 0);
        } else {
            CHECK(st.msg[0] != 0);
        }
        oc_arena_destroy(&a);
        free(data);
    }

    /* Loader-level: the coverage and OSV loaders get the malformed files
     * through the real CLI. No crash, honest exit. */
    const char *oc = OC_OC_BIN;
    char cmd[1100];
    static const char *COV[] = {"coverage_truncated.json", "coverage_huge_numbers.json",
                                "coverage_wrong_types.json", "coverage_empty.json"};
    for (size_t i = 0; i < sizeof(COV) / sizeof(COV[0]); i++) {
        snprintf(cmd, sizeof(cmd),
                 "%s check examples --packs-dir %s --coverage %s/tests/"
                 "fixtures_fuzz/json/%s",
                 oc, OC_REPO_ROOT "/packs", OC_REPO_ROOT, COV[i]);
        int r;
        char *o = run_cmd_capture(cmd, &r);
        CHECK(rc_honest(r));
        CHECK(!rc_crashed(r));
        free(o);
    }
    static const char *OSV[] = {"osv_truncated.json", "osv_wrong_schema.json",
                                "osv_records_not_array.json", "dup_keys.json", "nul_fuzz.json"};
    for (size_t i = 0; i < sizeof(OSV) / sizeof(OSV[0]); i++) {
        snprintf(cmd, sizeof(cmd),
                 "%s check tests/fixtures/supply --packs-dir %s "
                 "--osv-snapshot %s/tests/fixtures_fuzz/json/%s",
                 oc, OC_REPO_ROOT "/packs", OC_REPO_ROOT, OSV[i]);
        int r;
        char *o = run_cmd_capture(cmd, &r);
        CHECK(rc_honest(r));
        CHECK(!rc_crashed(r));
        free(o);
    }
    fprintf(stderr, "  loaders: %zu malformed JSON inputs handled honestly\n",
            sizeof(FILES) / sizeof(FILES[0]));
}

/* ------------------------------------------------------ compat fuzz ---- */

static void test_compat_self_fuzz(void) {
    /* Compat on the adversarial corpus against itself: garbage in both
     * trees must produce a verdict (SAFE here -- identical trees), never
     * a crash. */
    const char *oc = OC_OC_BIN;
    char cmd[1100];
    const char *fuzz = OC_REPO_ROOT "/tests/fixtures_fuzz";
    snprintf(cmd, sizeof(cmd),
             "%s compat --baseline '%s/js' --current '%s/js' "
             "--packs-dir %s",
             oc, fuzz, fuzz, OC_REPO_ROOT "/packs");
    int r;
    char *o = run_cmd_capture(cmd, &r);
    CHECK(rc_honest(r));
    CHECK(!rc_crashed(r));
    if (r == 0)
        CHECK(strstr(o ? o : "", "\"SAFE\"") != NULL);
    free(o);
}

int main(void) {
    oc_arena_init(&g_arena);

    test_fuzz_pipeline();
    test_adversarial_corpus();
    test_json_loader_fuzz();
    test_compat_self_fuzz();

    oc_arena_destroy(&g_arena);
    TEST_SUMMARY();
    return check_fail ? 1 : 0;
}
