#!/usr/bin/env python3
"""M5 GA determinism audit (plan Table 9 / P4): the FULL 10k-file corpus
must produce BYTE-IDENTICAL reports across

  - repeated runs of the same binary (Release cells run twice each --
    the repeated-run determinism claim),
  - the gcc-Release and clang-Release builds (cross-compiler),
  - the gcc-Sanitize and clang-Sanitize builds (Debug + ASan/UBSan)
    vs Release (cross-preset; one run each -- sanitizer cells exist for
    byte-identity, the repeated-run claim is a Release-cell claim).

Any digest mismatch is a hard FAIL. The corpus is regenerated by the
committed deterministic generator (scripts/perf_gen.py) and its content
digest is recorded so the audit is replayable against the same bytes.

Additionally records single-core wall time per run (the sprint budget
90 s and the M2 target 60 s are re-affirmed on the same measurement).

Usage:
  python3 scripts/acceptance/determinism_audit.py \
      [--oc BINARY]... [--corpus DIR] [--verdict docs/evidence/determinism_audit.json]

Exit 0 iff every digest matches.
"""
import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import time

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def corpus_digest(corpus):
    """Digest over the sorted (relpath, file-digest) pairs -- deterministic
    content identity for the whole tree."""
    h = hashlib.sha256()
    entries = []
    for dirpath, _dirs, files in os.walk(corpus):
        for name in files:
            p = os.path.join(dirpath, name)
            entries.append((os.path.relpath(p, corpus), sha256_file(p)))
    entries.sort()
    for rel, dig in entries:
        h.update(rel.encode())
        h.update(dig.encode())
    return h.hexdigest(), len(entries)


def run_scan(oc, corpus, packs):
    cmd = ["taskset", "-c", "0", oc, "check", corpus, "--packs-dir", packs]
    t0 = time.time()
    p = subprocess.run(cmd, capture_output=True, timeout=600)
    wall = time.time() - t0
    if p.returncode not in (0, 1, 2):
        raise RuntimeError(f"{oc} exited {p.returncode}: {p.stderr[:300].decode()}")
    if not p.stdout:
        # An empty report is NEVER a legitimate scan result (even a clean
        # scan prints the report JSON). exit 2 + empty stdout is what oc
        # prints when the corpus path vanished (e.g. a /tmp cleaner); it
        # must fail the audit LOUDLY, not count the empty-string digest as
        # a 'second determinism digest' (caught in the M4 gate-day dogfood,
        # 2026-11-19: the sandbox wiped /tmp mid-audit).
        raise RuntimeError(f"{oc} produced an EMPTY report (exit {p.returncode}): "
                           f"{p.stderr[:300].decode()}")
    out = "/tmp/oc_audit_report.json"
    with open(out, "wb") as f:
        f.write(p.stdout)
    return sha256_file(out), len(p.stdout), wall, p.returncode


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--oc", action="append", default=[],
                    help="oc binary to audit; repeatable (default: all build/*/oc)")
    ap.add_argument("--corpus", default=None, help="reuse an existing corpus dir")
    ap.add_argument("--keep-corpus", action="store_true")
    ap.add_argument("--verdict", default="docs/evidence/determinism_audit.json")
    ap.add_argument("--sanitize-runs", type=int, default=1,
                    help="runs per sanitize cell (default 1; Release always 2)")
    args = ap.parse_args()

    binaries = args.oc or [
        os.path.join(REPO_ROOT, "build", cell, "oc")
        for cell in ("default", "sanitize", "clang-release", "clang-sanitize")
        if os.path.exists(os.path.join(REPO_ROOT, "build", cell, "oc"))
    ]
    if len(binaries) < 2:
        print("need at least two oc builds for a cross-build audit", file=sys.stderr)
        return 1

    packs = os.path.join(REPO_ROOT, "packs")
    made_here = False
    if args.corpus:
        corpus = os.path.abspath(args.corpus)
    else:
        # work/ survives within a session; /tmp does NOT (sandbox tmp
        # cleaners have wiped mid-audit corpora -- M4 dogfood, 2026-11-19).
        # work/ is gitignored scratch; the corpus is disposable.
        corpus = os.path.join(REPO_ROOT, "work", "audit_corpus")
        shutil.rmtree(corpus, ignore_errors=True)
        os.makedirs(os.path.dirname(corpus), exist_ok=True)
        subprocess.run([sys.executable, os.path.join(REPO_ROOT, "scripts", "perf_gen.py"),
                        corpus], check=True, capture_output=True)
        made_here = True

    cdig, nfiles = corpus_digest(corpus)
    print(f"corpus: {nfiles} files, content digest {cdig[:16]}...")

    verdict = {
        "schema": "omnicheck.evidence/v0",
        "audit": "M5 GA determinism audit (full corpus, cross-build)",
        "corpus": {"files": nfiles, "digest": cdig},
        "runs": [],
        "all_identical": False,
    }
    digests = set()
    all_ok = True
    for oc_bin in binaries:
        label = os.path.relpath(oc_bin, REPO_ROOT)
        # Release cells: two runs (the repeated-run claim). Sanitize
        # cells: one run per --sanitize-runs (cross-preset identity).
        reps = 2 if "sanitize" not in label else max(1, args.sanitize_runs)
        for rep in range(1, reps + 1):
            dig, size, wall, rc = run_scan(oc_bin, corpus, packs)
            digests.add(dig)
            verdict["runs"].append({
                "binary": label, "run": rep, "report_sha256": dig,
                "report_bytes": size, "wall_seconds": round(wall, 2),
                "exit": rc,
            })
            print(f"  {label} run {rep}: {dig[:16]}... {size} bytes, {wall:.2f}s, exit {rc}")
            all_ok &= rc in (0, 1, 2)

    verdict["distinct_digests"] = len(digests)
    verdict["all_identical"] = all_ok and len(digests) == 1
    # Budgets are measured on RELEASE builds only: the sanitize cells run
    # Debug + ASan/UBSan, whose 10x overhead is sanitizer cost, not engine
    # cost -- they are recorded for byte-identity, never for wall time.
    release_walls = [r["wall_seconds"] for r in verdict["runs"]
                     if "sanitize" not in r["binary"]]
    worst = max(release_walls) if release_walls else max(
        r["wall_seconds"] for r in verdict["runs"])
    verdict["budget_check"] = {
        "worst_release_wall_seconds": worst,
        "worst_sanitize_wall_seconds": max(r["wall_seconds"] for r in verdict["runs"]
                                           if "sanitize" in r["binary"]),
        "sprint_gate_90s": worst < 90.0,
        "m2_target_60s": worst < 60.0,
        "note": "single-core (taskset -c 0), Release cells only",
    }
    print(f"distinct report digests: {len(digests)} "
          f"({'BYTE-IDENTICAL' if len(digests) == 1 else 'MISMATCH'})")
    print(f"worst single-core wall: {worst:.2f}s (gate 90s, target 60s)")

    out = os.path.join(REPO_ROOT, args.verdict)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        json.dump(verdict, f, indent=1, sort_keys=True)
        f.write("\n")
    print("verdict written:", os.path.relpath(out, REPO_ROOT))

    if made_here and not args.keep_corpus:
        shutil.rmtree(corpus, ignore_errors=True)
    return 0 if verdict["all_identical"] else 1


if __name__ == "__main__":
    sys.exit(main())
